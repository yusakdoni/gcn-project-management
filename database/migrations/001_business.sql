-- GCN Monitor student MVP. All amounts are whole IDR (INTEGER).
CREATE TABLE IF NOT EXISTS projects (
 id INTEGER PRIMARY KEY AUTOINCREMENT,
 code TEXT NOT NULL UNIQUE,
 name TEXT NOT NULL,
 client TEXT NOT NULL DEFAULT '',
 manager TEXT NOT NULL DEFAULT '',
 status TEXT NOT NULL DEFAULT 'Perencanaan',
 progress INTEGER NOT NULL DEFAULT 0 CHECK(progress BETWEEN 0 AND 100),
 start_date TEXT,
 due_date TEXT,
 contract_amount INTEGER NOT NULL DEFAULT 0 CHECK(contract_amount >= 0),
 budget_amount INTEGER NOT NULL DEFAULT 0 CHECK(budget_amount >= 0),
 created_by INTEGER REFERENCES users(id) ON DELETE SET NULL,
 created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS project_assignments (
 project_id INTEGER NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
 user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 assignment_role TEXT NOT NULL CHECK(assignment_role IN ('pic','member')),
 created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
 PRIMARY KEY(project_id,user_id)
);
CREATE TABLE IF NOT EXISTS expenses (
 id INTEGER PRIMARY KEY AUTOINCREMENT,
 project_id INTEGER NOT NULL REFERENCES projects(id) ON DELETE RESTRICT,
 category TEXT NOT NULL,
 description TEXT NOT NULL,
 amount INTEGER NOT NULL CHECK(amount > 0),
 expense_date TEXT NOT NULL,
 status TEXT NOT NULL DEFAULT 'DRAFT' CHECK(status IN ('DRAFT','PENDING_APPROVAL','APPROVED','REJECTED','CANCEL_PENDING','CANCELLED')),
 created_by INTEGER NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
 created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_expenses_project_status ON expenses(project_id,status);
CREATE TABLE IF NOT EXISTS expense_attachments (
 id INTEGER PRIMARY KEY AUTOINCREMENT,
 expense_id INTEGER NOT NULL REFERENCES expenses(id) ON DELETE RESTRICT,
 storage_key TEXT NOT NULL UNIQUE,
 original_name TEXT NOT NULL,
 mime_type TEXT NOT NULL,
 size_bytes INTEGER NOT NULL CHECK(size_bytes > 0),
 uploaded_by INTEGER NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
 created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS approval_history (
 id INTEGER PRIMARY KEY AUTOINCREMENT,
 expense_id INTEGER NOT NULL REFERENCES expenses(id) ON DELETE RESTRICT,
 actor_id INTEGER NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
 action TEXT NOT NULL,
 from_status TEXT NOT NULL,
 to_status TEXT NOT NULL,
 reason TEXT,
 created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS notifications (
 id INTEGER PRIMARY KEY AUTOINCREMENT,
 user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 expense_id INTEGER REFERENCES expenses(id) ON DELETE CASCADE,
 message TEXT NOT NULL,
 read_at TEXT,
 created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS expense_audit_logs (
 id INTEGER PRIMARY KEY AUTOINCREMENT,
 expense_id INTEGER NOT NULL REFERENCES expenses(id) ON DELETE RESTRICT,
 actor_id INTEGER NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
 action TEXT NOT NULL,
 details TEXT,
 created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
);
